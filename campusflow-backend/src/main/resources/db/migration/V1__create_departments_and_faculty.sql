CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    code VARCHAR(20) NOT NULL,
    description VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_departments_code UNIQUE (code),
    CONSTRAINT ck_departments_name CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_departments_code CHECK (length(trim(code)) > 0)
);

CREATE TABLE faculty (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    employee_code VARCHAR(30) NOT NULL,
    designation VARCHAR(100),
    department_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_faculty_email UNIQUE (email),
    CONSTRAINT uk_faculty_employee_code UNIQUE (employee_code),
    CONSTRAINT fk_faculty_department FOREIGN KEY (department_id)
        REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT ck_faculty_name CHECK (length(trim(full_name)) > 0),
    CONSTRAINT ck_faculty_email CHECK (length(trim(email)) > 0),
    CONSTRAINT ck_faculty_employee_code CHECK (length(trim(employee_code)) > 0)
);

CREATE INDEX idx_faculty_department_id ON faculty (department_id);
CREATE INDEX idx_faculty_active ON faculty (active);
