CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    faculty_id BIGINT UNIQUE REFERENCES faculty(id) ON DELETE RESTRICT,
    student_id BIGINT UNIQUE REFERENCES students(id) ON DELETE RESTRICT,
    security_version BIGINT NOT NULL DEFAULT 0 CHECK (security_version >= 0),
    password_changed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_account_email UNIQUE (email),
    CONSTRAINT ck_account_email CHECK (email = lower(trim(email)) AND length(trim(email)) > 0),
    CONSTRAINT ck_account_password_hash CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    CONSTRAINT ck_account_role_link CHECK (
        (role = 'ADMIN' AND faculty_id IS NULL AND student_id IS NULL) OR
        (role = 'FACULTY' AND faculty_id IS NOT NULL AND student_id IS NULL) OR
        (role = 'STUDENT' AND student_id IS NOT NULL AND faculty_id IS NULL))
);
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE RESTRICT,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_refresh_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_refresh_user ON refresh_tokens(user_account_id);
CREATE INDEX idx_refresh_expiry ON refresh_tokens(expires_at);
