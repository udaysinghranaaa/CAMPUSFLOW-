CREATE TABLE academic_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (length(trim(name)) > 0),
    start_year INTEGER NOT NULL CHECK (start_year BETWEEN 1900 AND 9999),
    end_year INTEGER NOT NULL CHECK (end_year BETWEEN 1900 AND 9999 AND end_year > start_year),
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_batch_id_department UNIQUE (id, department_id)
);
CREATE UNIQUE INDEX uk_batch_department_name ON academic_batches(department_id, lower(name));

CREATE TABLE academic_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL CHECK (length(trim(name)) > 0),
    batch_id BIGINT NOT NULL REFERENCES academic_batches(id) ON DELETE RESTRICT,
    capacity INTEGER CHECK (capacity > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_section_id_batch UNIQUE (id, batch_id)
);
CREATE UNIQUE INDEX uk_section_batch_name ON academic_sections(batch_id, lower(name));

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_number VARCHAR(40) NOT NULL,
    roll_number VARCHAR(30) NOT NULL,
    full_name VARCHAR(150) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL,
    phone_number VARCHAR(25),
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    batch_id BIGINT NOT NULL,
    section_id BIGINT,
    current_semester INTEGER NOT NULL CHECK (current_semester > 0),
    admission_year INTEGER NOT NULL CHECK (admission_year BETWEEN 1900 AND 9999),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'GRADUATED', 'SUSPENDED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_student_enrollment UNIQUE (enrollment_number),
    CONSTRAINT uk_student_email UNIQUE (email),
    CONSTRAINT uk_student_batch_roll UNIQUE (batch_id, roll_number),
    CONSTRAINT ck_student_enrollment CHECK (length(trim(enrollment_number)) > 0
        AND enrollment_number = upper(trim(enrollment_number))),
    CONSTRAINT ck_student_roll CHECK (length(trim(roll_number)) > 0
        AND roll_number = upper(trim(roll_number))),
    CONSTRAINT ck_student_email CHECK (length(trim(email)) > 0 AND email = lower(trim(email))),
    CONSTRAINT fk_student_batch_department FOREIGN KEY (batch_id, department_id)
        REFERENCES academic_batches(id, department_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_student_section_batch FOREIGN KEY (section_id, batch_id)
        REFERENCES academic_sections(id, batch_id) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX idx_student_department ON students(department_id);
CREATE INDEX idx_student_section_batch ON students(section_id, batch_id);
CREATE INDEX idx_student_status ON students(status);
CREATE INDEX idx_student_semester ON students(current_semester);
-- The batch/roll unique index also supports lookups by batch_id.

CREATE FUNCTION prevent_student_enrollment_change() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.enrollment_number IS DISTINCT FROM OLD.enrollment_number THEN
        RAISE EXCEPTION 'Student enrollment number is immutable'
            USING ERRCODE = '23514', CONSTRAINT = 'ck_student_enrollment_immutable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_student_enrollment_immutable BEFORE UPDATE OF enrollment_number ON students
    FOR EACH ROW EXECUTE FUNCTION prevent_student_enrollment_change();
