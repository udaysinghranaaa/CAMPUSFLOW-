-- Additive Phase 5. Campus-local dates/times; no extensions or privileged roles required.
CREATE TABLE subjects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(30) NOT NULL CHECK(code=upper(trim(code)) AND length(code)>0),
 name VARCHAR(150) NOT NULL CHECK(length(trim(name))>0),
 department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
 description VARCHAR(1000), active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT uk_subject_department_code UNIQUE(department_id,code)
);
CREATE TABLE rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE CHECK(code=upper(trim(code)) AND length(code)>0),
 name VARCHAR(150) NOT NULL CHECK(length(trim(name))>0), building VARCHAR(100) NOT NULL CHECK(length(trim(building))>0),
 floor VARCHAR(30), type VARCHAR(20) NOT NULL CHECK(type IN('CLASSROOM','LAB','SEMINAR')),
 capacity INTEGER NOT NULL CHECK(capacity>0), active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE academic_terms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL CHECK(length(trim(name))>0), department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
 semester INTEGER NOT NULL CHECK(semester>0), start_date DATE NOT NULL, end_date DATE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT ck_term_dates CHECK(end_date>=start_date AND end_date-start_date<=366),
 CONSTRAINT uk_term_scope UNIQUE(department_id,name,semester)
);
CREATE TABLE timetable_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 academic_term_id BIGINT NOT NULL REFERENCES academic_terms(id) ON DELETE RESTRICT,
 section_id BIGINT NOT NULL REFERENCES academic_sections(id) ON DELETE RESTRICT,
 subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
 faculty_id BIGINT NOT NULL REFERENCES faculty(id) ON DELETE RESTRICT,
 room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
 day_of_week INTEGER NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 start_time TIME NOT NULL, end_time TIME NOT NULL, effective_start_date DATE NOT NULL, effective_end_date DATE NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN('DRAFT','PUBLISHED','CANCELLED')),
 session_type VARCHAR(20) NOT NULL CHECK(session_type IN('LECTURE','PRACTICAL','TUTORIAL')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT ck_session_times CHECK(start_time<end_time),
 CONSTRAINT ck_session_dates CHECK(effective_end_date>=effective_start_date AND effective_end_date-effective_start_date<=366)
);
CREATE INDEX idx_session_term_section ON timetable_sessions(academic_term_id,section_id);
CREATE INDEX idx_session_faculty ON timetable_sessions(faculty_id,status);
CREATE INDEX idx_session_subject ON timetable_sessions(subject_id,status);
CREATE TABLE session_exceptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 timetable_session_id BIGINT NOT NULL REFERENCES timetable_sessions(id) ON DELETE RESTRICT,
 exception_date DATE NOT NULL, type VARCHAR(20) NOT NULL CHECK(type IN('CANCELLED','RESCHEDULED')),
 start_time TIME, end_time TIME, faculty_id BIGINT REFERENCES faculty(id) ON DELETE RESTRICT,
 room_id BIGINT REFERENCES rooms(id) ON DELETE RESTRICT, reason VARCHAR(500),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT uk_session_exception UNIQUE(timetable_session_id,exception_date),
 CONSTRAINT ck_exception_replacement CHECK((type='CANCELLED' AND start_time IS NULL AND end_time IS NULL AND faculty_id IS NULL AND room_id IS NULL)
 OR(type='RESCHEDULED' AND start_time IS NOT NULL AND end_time IS NOT NULL AND start_time<end_time AND faculty_id IS NOT NULL AND room_id IS NOT NULL))
);
CREATE TABLE faculty_unavailability (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 faculty_id BIGINT NOT NULL REFERENCES faculty(id) ON DELETE RESTRICT, block_date DATE NOT NULL,
 start_time TIME NOT NULL, end_time TIME NOT NULL, reason VARCHAR(500), active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT ck_block_times CHECK(start_time<end_time)
);
CREATE INDEX idx_block_faculty_date ON faculty_unavailability(faculty_id,block_date);
CREATE TABLE faculty_schedule_coverage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 academic_term_id BIGINT NOT NULL REFERENCES academic_terms(id) ON DELETE RESTRICT,
 faculty_id BIGINT NOT NULL REFERENCES faculty(id) ON DELETE RESTRICT,
 day_mask INTEGER NOT NULL CHECK(day_mask BETWEEN 1 AND 127), start_time TIME NOT NULL, end_time TIME NOT NULL,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT uk_coverage_faculty_term UNIQUE(faculty_id,academic_term_id), CONSTRAINT ck_coverage_times CHECK(start_time<end_time)
);
CREATE TABLE schedule_allocations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT REFERENCES timetable_sessions(id) ON DELETE RESTRICT,
 block_id BIGINT REFERENCES faculty_unavailability(id) ON DELETE RESTRICT,
 occurrence_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
 faculty_id BIGINT NOT NULL REFERENCES faculty(id) ON DELETE RESTRICT,
 room_id BIGINT REFERENCES rooms(id) ON DELETE RESTRICT,
 section_id BIGINT REFERENCES academic_sections(id) ON DELETE RESTRICT,
 during TSRANGE GENERATED ALWAYS AS(tsrange(occurrence_date+start_time,occurrence_date+end_time,'[)')) STORED,
 CONSTRAINT ck_allocation_owner CHECK((session_id IS NOT NULL AND block_id IS NULL AND room_id IS NOT NULL AND section_id IS NOT NULL)
 OR(session_id IS NULL AND block_id IS NOT NULL AND room_id IS NULL AND section_id IS NULL)),
 CONSTRAINT ck_allocation_time CHECK(start_time<end_time),
 CONSTRAINT uk_allocation_session_date UNIQUE(session_id,occurrence_date), CONSTRAINT uk_allocation_block UNIQUE(block_id),
 -- Built-in range GiST operators avoid requiring CREATE EXTENSION btree_gist privileges.
 CONSTRAINT ex_schedule_faculty EXCLUDE USING gist (numrange(faculty_id::numeric,faculty_id::numeric,'[]') WITH &&, during WITH &&),
 CONSTRAINT ex_schedule_room EXCLUDE USING gist (numrange(room_id::numeric,room_id::numeric,'[]') WITH &&, during WITH &&) WHERE(room_id IS NOT NULL),
 CONSTRAINT ex_schedule_section EXCLUDE USING gist (numrange(section_id::numeric,section_id::numeric,'[]') WITH &&, during WITH &&) WHERE(section_id IS NOT NULL)
);
CREATE INDEX idx_allocation_faculty_date ON schedule_allocations(faculty_id,occurrence_date);
CREATE INDEX idx_allocation_section_date ON schedule_allocations(section_id,occurrence_date);

CREATE FUNCTION check_timetable_session() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE term academic_terms%ROWTYPE; dep BIGINT; size INTEGER; enrolled INTEGER;
BEGIN
 IF NEW.status='CANCELLED' THEN RETURN NEW; END IF;
 SELECT * INTO STRICT term FROM academic_terms WHERE id=NEW.academic_term_id FOR SHARE;
 IF NOT term.active OR NEW.effective_start_date<term.start_date OR NEW.effective_end_date>term.end_date THEN
  RAISE EXCEPTION 'Invalid active term or session date range' USING ERRCODE='23514',CONSTRAINT='ck_session_term'; END IF;
 SELECT b.department_id,s.capacity INTO dep,size FROM academic_sections s JOIN academic_batches b ON b.id=s.batch_id
 WHERE s.id=NEW.section_id AND s.active AND b.active FOR SHARE OF s,b;
 IF dep IS NULL OR dep<>term.department_id OR NOT EXISTS(SELECT 1 FROM subjects WHERE id=NEW.subject_id AND active AND department_id=dep)
 OR NOT EXISTS(SELECT 1 FROM faculty WHERE id=NEW.faculty_id AND active AND department_id=dep) THEN
  RAISE EXCEPTION 'Invalid active academic references or department scope' USING ERRCODE='23514',CONSTRAINT='ck_session_scope'; END IF;
 SELECT count(*) INTO enrolled FROM students WHERE section_id=NEW.section_id AND status='ACTIVE';
 IF NOT EXISTS(SELECT 1 FROM rooms WHERE id=NEW.room_id AND active AND capacity>=greatest(coalesce(size,0),enrolled)) THEN
  RAISE EXCEPTION 'Inactive or undersized room' USING ERRCODE='23514',CONSTRAINT='ck_session_capacity'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_session_validate BEFORE INSERT OR UPDATE ON timetable_sessions FOR EACH ROW EXECUTE FUNCTION check_timetable_session();

CREATE FUNCTION rebuild_session_allocations(sid BIGINT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE s timetable_sessions%ROWTYPE;
BEGIN
 SELECT * INTO STRICT s FROM timetable_sessions WHERE id=sid FOR UPDATE;
 DELETE FROM schedule_allocations WHERE session_id=sid;
 IF s.status='CANCELLED' THEN RETURN; END IF;
 IF EXISTS(SELECT 1 FROM session_exceptions e JOIN faculty f ON f.id=e.faculty_id JOIN rooms r ON r.id=e.room_id
 WHERE e.timetable_session_id=s.id AND e.type='RESCHEDULED' AND (NOT f.active OR NOT r.active)) THEN
 RAISE EXCEPTION 'Inactive replacement resource' USING ERRCODE='23514',CONSTRAINT='ck_exception_active'; END IF;
 INSERT INTO schedule_allocations(session_id,occurrence_date,start_time,end_time,faculty_id,room_id,section_id)
 SELECT s.id,s.effective_start_date+n,coalesce(e.start_time,s.start_time),coalesce(e.end_time,s.end_time),
        coalesce(e.faculty_id,s.faculty_id),coalesce(e.room_id,s.room_id),s.section_id
 FROM generate_series(0,s.effective_end_date-s.effective_start_date) n
 LEFT JOIN session_exceptions e ON e.timetable_session_id=s.id AND e.exception_date=s.effective_start_date+n
 WHERE extract(isodow FROM s.effective_start_date+n)=s.day_of_week AND (e.id IS NULL OR e.type<>'CANCELLED')
 ORDER BY s.effective_start_date+n;
END $$;
CREATE FUNCTION refresh_session_allocations() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN PERFORM rebuild_session_allocations(NEW.id); RETURN NEW; END $$;
CREATE TRIGGER trg_session_allocations AFTER INSERT OR UPDATE ON timetable_sessions FOR EACH ROW EXECUTE FUNCTION refresh_session_allocations();
CREATE FUNCTION refresh_exception_allocations() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE s timetable_sessions%ROWTYPE; dep BIGINT; size INTEGER;
BEGIN
 SELECT * INTO STRICT s FROM timetable_sessions WHERE id=NEW.timetable_session_id FOR UPDATE;
 IF NEW.exception_date<s.effective_start_date OR NEW.exception_date>s.effective_end_date OR extract(isodow FROM NEW.exception_date)<>s.day_of_week THEN
 RAISE EXCEPTION 'Exception date is not an occurrence' USING ERRCODE='23514',CONSTRAINT='ck_exception_date'; END IF;
 IF NEW.type='RESCHEDULED' THEN
 SELECT t.department_id INTO dep FROM academic_terms t WHERE t.id=s.academic_term_id;
 SELECT greatest(coalesce(capacity,0),(SELECT count(*)::integer FROM students WHERE section_id=s.section_id AND status='ACTIVE')) INTO size FROM academic_sections WHERE id=s.section_id;
 IF NOT EXISTS(SELECT 1 FROM faculty WHERE id=NEW.faculty_id AND active AND department_id=dep)
 OR NOT EXISTS(SELECT 1 FROM rooms WHERE id=NEW.room_id AND active AND capacity>=size) THEN
 RAISE EXCEPTION 'Invalid replacement faculty/room' USING ERRCODE='23514',CONSTRAINT='ck_exception_scope'; END IF;
 END IF;
 PERFORM rebuild_session_allocations(s.id); RETURN NEW;
END $$;
CREATE TRIGGER trg_exception_allocations AFTER INSERT OR UPDATE ON session_exceptions FOR EACH ROW EXECUTE FUNCTION refresh_exception_allocations();
CREATE FUNCTION refresh_block_allocations() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 DELETE FROM schedule_allocations WHERE block_id=NEW.id;
 IF NEW.active THEN
 INSERT INTO schedule_allocations(block_id,occurrence_date,start_time,end_time,faculty_id)
 VALUES(NEW.id,NEW.block_date,NEW.start_time,NEW.end_time,NEW.faculty_id);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_block_allocations AFTER INSERT OR UPDATE ON faculty_unavailability FOR EACH ROW EXECUTE FUNCTION refresh_block_allocations();